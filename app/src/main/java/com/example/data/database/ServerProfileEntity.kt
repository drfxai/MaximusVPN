package com.example.data.database

import androidx.room.Entity
import androidx.room.Index
import androidx.room.PrimaryKey
import com.example.data.model.CanonicalFingerprint
import com.example.data.model.EngineType
import com.example.data.model.ProfileType
import com.example.data.model.ProtocolType
import com.example.data.model.ServerCategory
import com.example.data.model.VlessProfile
import com.example.data.security.SecureStorage

@Entity(
    tableName = "server_profiles",
    indices = [
        Index(value = ["canonicalFingerprint"]),
        Index(value = ["overallScore"]),
        Index(value = ["isFavorite"]),
        Index(value = ["category"])
    ]
)
data class ServerProfileEntity(
    @PrimaryKey val id: String,
    val canonicalFingerprint: String,
    val name: String,
    val address: String,
    val port: Int,
    val uuid: String,
    val encryption: String,
    val transport: String,
    val security: String,
    val sni: String,
    val host: String,
    val path: String,
    val serviceName: String,
    val flow: String,
    val fingerprint: String,
    val cipherSuites: String = "",
    val fakeSniPool: String = "",
    val desyncEnabled: Boolean = true,
    val desyncProfileName: String = "BALANCED",
    val desyncMethodName: String = "FAKE_SNI",
    val desyncSplitPosition: Int = 2,
    val publicKey: String,
    val shortId: String,
    val spiderX: String,
    val alpn: String,
    val headerType: String,
    val isFavorite: Boolean,
    val lastLatencyMs: Long?,
    val downloadMbps: Double = 0.0,
    val uploadMbps: Double = 0.0,
    val jitterMs: Long = 0,
    val packetLoss: Double = 0.0,
    val handshakeMs: Long = 0,
    val stability: Double = 100.0,
    val successRate: Double = 100.0,
    val speedScore: Double = 0.0,
    val latencyScore: Double = 0.0,
    val stabilityScore: Double = 0.0,
    val reliabilityScore: Double = 0.0,
    val overallScore: Double = 0.0,
    val category: String = ServerCategory.BALANCED.name,
    val lastTestedTimestamp: Long?,
    val countryCode: String?,
    val createdAt: Long,
    val profileType: String = ProfileType.VLESS.name,
    val protocolType: String = ProtocolType.VLESS.name,
    val engineType: String = EngineType.XRAY.name,
    val rawConfig: String = "",
    val subscriptionUrl: String? = null,
    val sourceSubscription: String? = null,
    val sourceFile: String? = null,
    val proxyGroupName: String? = null,
    val nodeCount: Int = 1
) {
    fun toDomain(): VlessProfile = VlessProfile(
        id = id,
        canonicalFingerprint = canonicalFingerprint,
        name = name,
        address = address,
        port = port,
        uuid = SecureStorage.decrypt(uuid),
        encryption = encryption,
        transport = transport,
        security = security,
        sni = sni,
        host = host,
        path = path,
        serviceName = serviceName,
        flow = flow,
        fingerprint = fingerprint,
        cipherSuites = cipherSuites,
        fakeSniPool = fakeSniPool,
        desyncEnabled = desyncEnabled,
        desyncProfileName = desyncProfileName,
        desyncMethodName = desyncMethodName,
        desyncSplitPosition = desyncSplitPosition,
        publicKey = SecureStorage.decrypt(publicKey),
        shortId = SecureStorage.decrypt(shortId),
        spiderX = SecureStorage.decrypt(spiderX),
        alpn = alpn,
        headerType = headerType,
        isFavorite = isFavorite,
        lastLatencyMs = lastLatencyMs,
        downloadMbps = downloadMbps,
        uploadMbps = uploadMbps,
        jitterMs = jitterMs,
        packetLoss = packetLoss,
        handshakeMs = handshakeMs,
        stability = stability,
        successRate = successRate,
        speedScore = speedScore,
        latencyScore = latencyScore,
        stabilityScore = stabilityScore,
        reliabilityScore = reliabilityScore,
        overallScore = overallScore,
        category = try { ServerCategory.valueOf(category) } catch (_: Exception) { ServerCategory.BALANCED },
        lastTestedTimestamp = lastTestedTimestamp,
        countryCode = countryCode,
        createdAt = createdAt,
        profileType = try { ProfileType.valueOf(profileType) } catch (_: Exception) { ProfileType.VLESS },
        protocolType = try { ProtocolType.valueOf(protocolType) } catch (_: Exception) { ProtocolType.VLESS },
        engineType = try { EngineType.valueOf(engineType) } catch (_: Exception) { EngineType.XRAY },
        rawConfig = if (rawConfig.isNotEmpty()) SecureStorage.decrypt(rawConfig) else "",
        subscriptionUrl = subscriptionUrl?.let { if (it.isNotEmpty()) SecureStorage.decrypt(it) else it },
        sourceSubscription = sourceSubscription,
        sourceFile = sourceFile,
        proxyGroupName = proxyGroupName,
        nodeCount = nodeCount
    )

    companion object {
        fun fromDomain(p: VlessProfile): ServerProfileEntity = ServerProfileEntity(
            id = p.id,
            canonicalFingerprint = if (p.canonicalFingerprint.isNotBlank()) p.canonicalFingerprint else CanonicalFingerprint.computeFromProfile(p),
            name = p.name,
            address = p.address,
            port = p.port,
            uuid = if (p.uuid.isNotEmpty()) SecureStorage.encrypt(p.uuid) else "",
            encryption = p.encryption,
            transport = p.transport,
            security = p.security,
            sni = p.sni,
            host = p.host,
            path = p.path,
            serviceName = p.serviceName,
            flow = p.flow,
            fingerprint = p.fingerprint,
            cipherSuites = p.cipherSuites,
            fakeSniPool = p.fakeSniPool,
            desyncEnabled = p.desyncEnabled,
            desyncProfileName = p.desyncProfileName,
            desyncMethodName = p.desyncMethodName,
            desyncSplitPosition = p.desyncSplitPosition,
            publicKey = if (p.publicKey.isNotEmpty()) SecureStorage.encrypt(p.publicKey) else "",
            shortId = if (p.shortId.isNotEmpty()) SecureStorage.encrypt(p.shortId) else "",
            spiderX = if (p.spiderX.isNotEmpty()) SecureStorage.encrypt(p.spiderX) else "",
            alpn = p.alpn,
            headerType = p.headerType,
            isFavorite = p.isFavorite,
            lastLatencyMs = p.lastLatencyMs,
            downloadMbps = p.downloadMbps,
            uploadMbps = p.uploadMbps,
            jitterMs = p.jitterMs,
            packetLoss = p.packetLoss,
            handshakeMs = p.handshakeMs,
            stability = p.stability,
            successRate = p.successRate,
            speedScore = p.speedScore,
            latencyScore = p.latencyScore,
            stabilityScore = p.stabilityScore,
            reliabilityScore = p.reliabilityScore,
            overallScore = p.overallScore,
            category = p.category.name,
            lastTestedTimestamp = p.lastTestedTimestamp,
            countryCode = p.countryCode,
            createdAt = p.createdAt,
            profileType = p.profileType.name,
            protocolType = p.protocolType.name,
            engineType = p.engineType.name,
            rawConfig = if (p.rawConfig.isNotEmpty()) SecureStorage.encrypt(p.rawConfig) else "",
            subscriptionUrl = p.subscriptionUrl?.let { if (it.isNotEmpty()) SecureStorage.encrypt(it) else it },
            sourceSubscription = p.sourceSubscription,
            sourceFile = p.sourceFile,
            proxyGroupName = p.proxyGroupName,
            nodeCount = p.nodeCount
        )
    }
}

